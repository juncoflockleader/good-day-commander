"""游戏 API 层的两个协议：技能看到什么（WorldView），技能能做什么（Commander）。

由游戏适配器实现（BWAPI、python-sc2，或自写的沙盒）。技能只依赖这两个协议，不碰引擎。
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable, Literal, Protocol, Sequence

from .types import Cost, Frame, Location, PlayerId, Point, Resources, Seconds, UnitId, UnitType


class UnitView(Protocol):
    """一个单位的只读快照。"""

    @property
    def id(self) -> UnitId: ...
    @property
    def type(self) -> UnitType: ...
    @property
    def owner(self) -> PlayerId: ...
    @property
    def pos(self) -> Point: ...
    @property
    def hp(self) -> float: ...
    @property
    def hp_max(self) -> float: ...
    @property
    def supply(self) -> float: ...
    @property
    def is_idle(self) -> bool: ...
    @property
    def is_flying(self) -> bool: ...
    @property
    def is_structure(self) -> bool: ...
    @property
    def is_complete(self) -> bool: ...          # 建筑是否建完
    @property
    def cargo(self) -> tuple[UnitId, ...]: ...  # 运输单位里装的
    @property
    def order(self) -> str | None: ...          # 当前在执行的命令，调试和汇报用

    def has_role(self, role: str) -> bool: ...  # types.ROLE_*


@dataclass(frozen=True)
class ThreatEstimate:
    """某点附近的敌方威胁，撤退条件靠它。"""

    enemy_count: int
    enemy_supply: float
    has_anti_air: bool
    has_detection: bool


Owner = Literal["me", "enemy", "neutral", "any"]
RouteMode = Literal["ground", "air", "air_edge"]   # air_edge：贴地图边绕，空投用


class WorldView(Protocol):
    """技能看到的世界，只读。含迷雾记忆，所以 enemy_structures_known 会返回早先看到过的东西。"""

    @property
    def frame(self) -> Frame: ...
    @property
    def seconds(self) -> Seconds: ...
    @property
    def me(self) -> PlayerId: ...

    # 语义解析
    def resolve(self, loc: Location) -> Point: ...

    # 单位
    def unit(self, uid: UnitId) -> UnitView | None: ...
    def my_units(self, type_or_role: UnitType | None = None) -> Sequence[UnitView]: ...
    def enemies_visible(self, near: Point | None = None, radius: float | None = None) -> Sequence[UnitView]: ...
    def enemy_structures_known(self) -> Sequence[UnitView]: ...
    def units_near(self, pos: Point, radius: float, owner: Owner = "any") -> Sequence[UnitView]: ...

    # 经济
    def resources(self) -> Resources: ...
    def cost(self, type_or_role: UnitType) -> Cost: ...

    # 地图与视野
    def is_visible(self, pos: Point) -> bool: ...
    def last_seen(self, pos: Point) -> Frame | None: ...
    def threat_at(self, pos: Point, radius: float) -> ThreatEstimate: ...
    def distance(self, a: Point, b: Point) -> float: ...
    def route(self, a: Point, b: Point, mode: RouteMode = "ground") -> Sequence[Point]: ...
    def speed(self, type_or_role: UnitType) -> float: ...   # 每游戏秒移动距离，估 ETA 用
    def can_place(self, structure: UnitType, at: Point) -> bool: ...
    def find_placement(self, structure: UnitType, near: Point) -> Point | None: ...


class Commander(Protocol):
    """技能能下的命令。粒度是"打谁、去哪"，走位集火由微操层接管。

    ctx.cmd 是租约限定版：命令里出现未租用的单位会抛 NotLeased。
    """

    def move(self, units: Iterable[UnitId], to: Point, queue: bool = False) -> None: ...
    def attack_move(self, units: Iterable[UnitId], to: Point, queue: bool = False) -> None: ...
    def attack(self, units: Iterable[UnitId], target: UnitId) -> None: ...
    def patrol(self, units: Iterable[UnitId], to: Point) -> None: ...
    def stop(self, units: Iterable[UnitId]) -> None: ...
    def hold(self, units: Iterable[UnitId]) -> None: ...
    def gather(self, worker: UnitId, resource: UnitId) -> None: ...
    def build(self, worker: UnitId, structure: UnitType, at: Point) -> bool: ...
    def train(self, producer: UnitId, unit: UnitType) -> bool: ...
    def research(self, structure: UnitId, upgrade: str) -> bool: ...
    def load(self, transport: UnitId, units: Iterable[UnitId]) -> None: ...
    def unload_all(self, transport: UnitId, at: Point) -> None: ...


@dataclass(frozen=True)
class Death:
    """一次死亡。适配器把它追加到一个列表里，执行器据此统计击杀和阵亡。
    真游戏的 API 通常不告诉你谁杀的，killer 允许是适配器的推断。"""

    frame: Frame
    victim: UnitId
    victim_owner: PlayerId
    victim_type: UnitType
    killer: UnitId | None
    killer_owner: PlayerId | None


class NotLeased(Exception):
    """技能试图指挥不属于自己租约的单位。"""
